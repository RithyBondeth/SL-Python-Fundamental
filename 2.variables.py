# Creating Variables
name = "Bondeth"
age = 22
isBoy = True

print("Name:", name)
print("Age:", age)
print("isBoy:", isBoy)

#Casting
x = str(3)    # x will be '3'
y = int(3)    # y will be 3
z = float(3)  # z will be 3.0

print("x:", x)
print("y:", y)
print("z:", z)

#Get Types
type_of_x = type(x)
type_of_y = type(y)
type_of_z = type(z)

print(type_of_x)
print(type_of_y)
print(type_of_z)